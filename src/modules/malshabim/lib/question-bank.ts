export type MalshabimQuizDraftQuestion = {
  question: string;
  answer: string;
  is_correct: boolean;
};

export function pickRandomQuestions(count = 15): MalshabimQuizDraftQuestion[] {
  const shuffled = [...QUESTION_BANK].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count).map((q) => ({
    question: q,
    answer: "",
    is_correct: false,
  }));
}

